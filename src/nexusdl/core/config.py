def generate_env_content() -> str:
    """Return the text of a fresh ``.env`` file with generated secrets.

    The three secrets are freshly generated on every call — this helper
    is intended for **one-shot** use by the CLI's ``nexusdl admin init``
    command, not for per-startup generation. Regenerating the
    ``cookie_encryption_key`` after a first run would invalidate every
    cookie the ``CookieManager`` has stored.

    Returns:
        A complete ``.env`` file content: a leading comment block
        explaining the file, followed by the three ``NEXUSDL_*``
        assignments in the format the loader reads.
    """
    return (
        "# NexusDL secrets — generated by `nexusdl admin init`.\n"
        "# Never commit this file to version control.\n"
        "#\n"
        "# Regenerating cookie_encryption_key invalidates every stored\n"
        "# cookie in ~/.local/share/nexusdl/cookies.enc (or its per-OS\n"
        "# equivalent). Back up the file before rotating.\n"
        f"NEXUSDL_SECRET_KEY={secrets.token_urlsafe(32)}\n"
        f"NEXUSDL_JWT_SECRET={secrets.token_urlsafe(32)}\n"
        f"NEXUSDL_COOKIE_ENCRYPTION_KEY={Fernet.generate_key().decode()}\n"
    )


def bootstrap_env_file(
    path: Path,
    *,
    overwrite: bool = False,
) -> Path:
    """Create a ``.env`` file with fresh secrets, if it does not exist.

    The sanctioned entry point for a first-run setup: the CLI calls
    this before the first ``Settings()`` instantiation. Once the file
    exists with the three secrets, subsequent ``Settings()`` calls
    succeed without further bootstrap.

    The file is written with mode ``0o600`` on POSIX (owner-read-write
    only) — the secrets are not world-readable. On Windows the
    ``chmod`` call sets the read-only bit; the OS-level ACL model
    provides the actual protection.

    Args:
        path: Destination path (typically ``.env`` in the working
            directory).
        overwrite: When ``True``, replace an existing file even if it
            already has content. Intended for an explicit
            ``nexusdl admin regenerate-secrets`` command that the
            operator has confirmed is what they want — otherwise,
            the file is left untouched.

    Returns:
        *path*, unchanged, so the caller can log it.

    Raises:
        OSError: If the file cannot be written or the parent directory
            cannot be created.
    """
    if path.is_file() and not overwrite:
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate_env_content(), encoding="utf-8")
    try:
        os.chmod(path, 0o600)
    except OSError as exc:
        # Non-POSIX filesystems may reject the chmod; the write itself
        # already succeeded, and the secrets are still in the file.
        # The operator's filesystem permissions are their own concern,
        # but the failure should be visible, not silently swallowed.
        warnings.warn(
            f"Could not set 0600 permissions on {path}: {exc}",
            stacklevel=2,
        )
    return path


