class ContentSection(_Section):
    """Content filtering policy applied across the pipeline.

    The policy is a **user choice**, not a moral restriction of the code
    — the PROMPT MASTER's contract makes this explicit. The pipeline
    serves general-audience and adult content alike; these fields let
    an operator narrow what their deployment serves, not what NexusDL
    is capable of.

    Attributes:
        allow_adult: When ``False``, sites with
            :attr:`~nexusdl.core.models.site.SiteConfig.adult == True`
            are excluded by :class:`SiteRegistry` and by
            :class:`LibrarySearch`. When ``True`` (the default — matching
            the project's stated audience), no filter is applied.
        default_language: Fallback language when a source does not
            declare one. Used by :class:`LibrarySearch` and by the
            ``SearchFilters`` defaults at the CLI layer.
        max_content_rating: Highest content rating permitted when
            ``allow_adult`` is ``True``. Defaults to
            :attr:`ContentRating.PORNOGRAPHIC` — the widest value,
            preserving the "no restriction" default. A deployment that
            wants to serve adult content but exclude the most explicit
            tier sets this to :attr:`ContentRating.EROTICA`.
    """

    allow_adult: bool = True
    default_language: Language = Language.EN
    max_content_rating: ContentRating = ContentRating.PORNOGRAPHIC


