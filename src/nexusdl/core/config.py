class ProxySection(_Section):
    """Proxy pool configuration.

    Consumed by
    :func:`nexusdl.core.session.proxy_manager.load_proxy_configs` (which
    takes this object and returns :class:`ProxyConfig` instances). The
    exact attribute names match that function's contract — see its
    docstring for the "single URL first, then the list" ordering rule.

    **Proxy URLs are secrets.** Any embedded ``user:password@`` component
    must never reach a log, a diagnostic endpoint, or an exported config
    file. The values are typed as :class:`pydantic.SecretStr`; the only
    sanctioned way to recover the plaintext is
    ``config.url.get_secret_value()``, called exclusively by
    :class:`~nexusdl.core.session.http_session.HttpSession` at the
    moment of use.

    Attributes:
        enabled: Master switch. When ``False``, no proxy pool is
            constructed.
        url: Optional single proxy URL. When both ``url`` and ``urls``
            are set, ``url`` is placed first in the pool (matching
            ``load_proxy_configs``'s contract).
        urls: Optional list of additional proxy URLs, forming a
            rotation pool.
        strategy: Rotation strategy for fresh picks — ``"round_robin"``
            (the default) or ``"random"``. Enforced by
            :class:`~nexusdl.core.session.proxy_manager.ProxyManager`.
        sticky: Whether to bind a site to its first proxy until the
            proxy is benched. ``True`` by default — a session that
            switches proxies mid-chapter is a bug, not a feature.
        failure_threshold: Consecutive failures that bench a proxy.
        cooldown_seconds: How long a benched proxy stays excluded.
    """

    enabled: bool = False
    url: SecretStr | None = None
    urls: list[SecretStr] = Field(default_factory=list)
    strategy: Literal["round_robin", "random"] = "round_robin"
    sticky: bool = True
    failure_threshold: int = Field(default=3, ge=1)
    cooldown_seconds: float = Field(default=300.0, ge=0)


