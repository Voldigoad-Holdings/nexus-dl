class _PackageYamlSource(PydanticBaseSettingsSource):
    """A settings source that reads a YAML file bundled inside the package.

    Unlike :class:`_UserYamlSource`, which reads from an absolute path on
    the filesystem, this source reads from :mod:`importlib.resources` so
    it works identically whether the package is installed as a wheel,
    imported from a source tree, or running from a ``pip install -e``
    checkout.

    A missing or malformed YAML file is a soft failure — the source
    returns ``{}`` and the caller's other sources fill the gaps. This
    matches the "config should never crash startup" contract of the
    other loaders.
    """

    def get_field_value(
        self, field: Any, field_name: str
    ) -> tuple[Any, str, bool]:
        """Unused — :meth:`__call__` is overridden to return the whole dict."""
        return None, field_name, False

    def __call__(self) -> dict[str, Any]:
        """Load the bundled default configuration.

        Returns:
            The parsed YAML document, or ``{}`` if it cannot be located
            or parsed.
        """
        try:
            resource = (
                _resource_files(_DEFAULT_YAML_PACKAGE)
                / _DEFAULT_YAML_FILENAME
            )
            text = resource.read_text(encoding="utf-8")
        except (ModuleNotFoundError, FileNotFoundError, OSError):
            return {}
        try:
            data = yaml.safe_load(text)
        except yaml.YAMLError:
            return {}
        if not isinstance(data, dict):
            return {}
        return data


class _UserYamlSource(PydanticBaseSettingsSource):
    """A settings source that reads a YAML file from an absolute path.

    A missing file is a soft failure — a first-run deployment with no
    ``config.yaml`` is expected. A malformed file is also a soft
    failure, on the grounds that a startup failure for a broken config
    is often worse than starting with the defaults and reporting the
    problem in a log line.
    """

    def __init__(
        self,
        settings_cls: type[BaseSettings],
        path: Path,
    ) -> None:
        super().__init__(settings_cls)
        self._path = path

    def get_field_value(
        self, field: Any, field_name: str
    ) -> tuple[Any, str, bool]:
        """Unused — :meth:`__call__` is overridden to return the whole dict."""
        return None, field_name, False

    def __call__(self) -> dict[str, Any]:
        """Load the user configuration file.

        Returns:
            The parsed YAML document, or ``{}`` if it does not exist or
            cannot be parsed.
        """
        if not self._path.is_file():
            return {}
        try:
            with self._path.open("r", encoding="utf-8") as fh:
                data = yaml.safe_load(fh)
        except (OSError, yaml.YAMLError):
            return {}
        if not isinstance(data, dict):
            return {}
        return data


