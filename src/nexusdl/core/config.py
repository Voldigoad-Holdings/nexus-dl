"""Application-wide settings, loaded in a documented precedence order.

:class:`Settings` is the **single source of truth** for every tunable knob
in NexusDL. It is a Pydantic Settings v2 model that loads its values from
four sources, listed from highest to lowest priority:

1. **Constructor keyword arguments** — used by tests and by callers that
   want a specific override.
2. **Environment variables** — prefixed ``NEXUSDL_``, case-insensitive,
   with ``__`` as the nested delimiter (``NEXUSDL_DOWNLOADER__MAX_CONCURRENT_PAGES=8``).
3. **``.env`` file at the working directory** — the standard 12-factor
   secrets holder; generated by :func:`bootstrap_env_file` on first run.
4. **User configuration YAML** — ``<user_config_dir>/config.yaml``
   (per :mod:`platformdirs`).
5. **Bundled default YAML** — ``nexusdl/data/default_config.yaml``.

Any value not provided by these sources uses the Pydantic field default,
which is documented to match the bundled YAML. The result is that a fresh
install with no ``.env`` and no ``config.yaml`` produces a fully-populated
:class:`Settings` object, provided the caller has generated an ``.env``
with the three required secrets (see :func:`bootstrap_env_file`).

Secrets handling
----------------
Three fields are **required secrets** and have no default:

* :attr:`Settings.secret_key` — the general-purpose application key
  (session signing, CSRF tokens, plugin integrity checks).
* :attr:`Settings.jwt_secret` — the JWT signing key for the REST API.
* :attr:`Settings.cookie_encryption_key` — the Fernet key used by
  :class:`~nexusdl.core.session.cookie_manager.CookieManager`.

All three are stored as :class:`pydantic.SecretStr`, which redacts them
in ``repr``, ``str``, and ``model_dump``. They are validated at
construction time: empty values raise, and :attr:`cookie_encryption_key`
must be a valid 44-character Fernet key.

The **only sanctioned way to generate these values** is
:func:`bootstrap_env_file`, which the CLI's ``nexusdl admin init``
subcommand calls on first run. Generating them by hand is possible but
not recommended — the Fernet key in particular has exact size and
encoding requirements that are easy to get wrong.

Frozen, by design
-----------------
:class:`Settings` and every section model are declared
``model_config = ConfigDict(frozen=True, extra="forbid")``. A caller
that needs a modified copy uses :meth:`pydantic.BaseModel.model_copy`::

    modified = settings.model_copy(
        update={"app": settings.app.model_copy(update={"debug": False})}
    )

The freeze is deliberate: a :class:`Settings` instance is passed to every
module in the pipeline, and a stray ``settings.downloader.max_concurrent_pages
= 8`` from one coroutine must not silently change the behaviour of the
others. Configuration is set once at startup and read for the process
lifetime.

``extra="forbid"`` is equally deliberate — a typo in an env var name
(``NEXUSDL_DOWNLOADR__MAX_CONCURRENT_PAGES``) or a YAML key
(``downlaoder:``) fails at startup rather than being silently ignored.
The cost (a slightly noisier first-run experience) is far less than the
cost of a production deployment running with an unexpected default
because a config key was misspelled.

Nested sections
---------------
The 20+ configuration sections mirror the modules that consume them.
Every section is a plain :class:`pydantic.BaseModel` — not a
:class:`BaseSettings` — because only the top-level
:class:`Settings` participates in source loading. A section's fields are
populated from a nested dict produced by one of the loaders (env, YAML,
kwargs).

See the module-level constants and the individual section docstrings for
the meaning of each field.

Module path defaults
--------------------
:class:`PathsSection` computes sensible per-OS defaults via
:mod:`platformdirs`::

    user_data_dir     ~/.local/share/nexusdl          (Linux)
                      ~/Library/Application Support/nexusdl  (macOS)
                      %LOCALAPPDATA%\\nexusdl            (Windows)
    user_config_dir   ~/.config/nexusdl
    user_cache_dir    ~/.cache/nexusdl
    user_log_dir      ~/.local/state/nexusdl/log

Every path field is a plain :class:`pathlib.Path` and can be overridden
via ``NEXUSDL_PATHS__<FIELD>``. Note that the derived paths
(:attr:`PathsSection.cookies_file`, :attr:`database_file`, etc.) use
their own ``default_factory`` against the *default* base directory, not
against :attr:`user_data_dir`. A caller that overrides ``user_data_dir``
must also override the derived paths it cares about — documenting this
trade-off is cheaper than implementing a full path-derivation graph in
a frozen Pydantic model.

Cross-section validation
------------------------
:meth:`_validate_cross_section` enforces one cross-section rule that
cannot be expressed as a per-field constraint:

* If ``proxy.enabled`` is ``True``, at least one of ``proxy.url`` or
  ``proxy.urls`` must be non-empty. A proxy-enabled configuration with
  no proxy URL is a caller bug that would surface as a stack of
  "connection refused" errors on the first request; rejecting it at
  startup is strictly better.

Every other invariant is field-local and expressed via standard
Pydantic constraints (``ge=``, ``le=``, ``Literal[...]``,
``field_validator``).

Dependency graph (no cycles)::

    core.models.enums  ──►  core.config
    pydantic, pydantic-settings, platformdirs, PyYAML,
    cryptography (Fernet key generation in bootstrap)

No dependency on any other ``nexusdl.core`` module — this file is a
**leaf** on the project side and sits at the top of the domain
dependency graph (models depend on nothing, config depends on models).
"""

