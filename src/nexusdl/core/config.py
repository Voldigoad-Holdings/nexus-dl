class HttpSection(_Section):
    """HTTP client tuning, applied to every :class:`HttpSession` instance.

    The defaults match
    :data:`nexusdl.core.session.http_session.DEFAULT_TIMEOUTS` and the
    ``httpx.AsyncClient`` defaults the session uses when nothing is
    overridden.

    Attributes:
        connect_timeout: Seconds to establish the TCP/TLS connection.
        read_timeout: Seconds to wait for a chunk of response data.
        write_timeout: Seconds to upload a request body.
        pool_timeout: Seconds to wait for a connection from the pool
            when all are busy.
        http2: Enable HTTP/2. Requires the ``httpx[http2]`` extra, which
            is a runtime dependency of the project.
        follow_redirects: Follow 3xx responses automatically.
        max_connections: Maximum concurrent connections in the pool.
        max_keepalive_connections: Connections kept alive between
            requests.
        user_agent: Optional UA override. ``None`` (the default) lets
            the :class:`UserAgentRotator` pick one per request. A value
            disables rotation entirely and uses this UA for every
            request — useful for a site that has negotiated a specific
            agent.
    """

    connect_timeout: float = Field(default=10.0, gt=0)
    read_timeout: float = Field(default=30.0, gt=0)
    write_timeout: float = Field(default=30.0, gt=0)
    pool_timeout: float = Field(default=10.0, gt=0)
    http2: bool = True
    follow_redirects: bool = True
    max_connections: int = Field(default=100, ge=1)
    max_keepalive_connections: int = Field(default=20, ge=0)
    user_agent: str | None = None


