class _Section(BaseModel):
    """Common base for every configuration section.

    Every section shares the same model configuration:

    * ``frozen=True`` — the section is immutable after construction.
    * ``extra="forbid"`` — a typo in a nested key fails at startup.
    * ``str_strip_whitespace=True`` — leading/trailing whitespace on
      string values is trimmed, which prevents the classic
      ``NEXUSDL_APP__NAME=" NexusDL "`` footgun.

    Sections that need to override a validator or add a field-level
    constraint do so on the subclass; they do not replace this config.
    """

    model_config = ConfigDict(
        frozen=True,
        extra="forbid",
        str_strip_whitespace=True,
    )


