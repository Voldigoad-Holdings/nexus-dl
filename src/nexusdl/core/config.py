class RateLimitsSection(_Section):
    """Default rate limiting policy, before per-site overrides.

    The ``HttpSession`` combines this with
    :attr:`~nexusdl.core.models.site.SiteConfig.rate_limit` at request
    time. The value from the site config always wins when present; this
    section provides the fallback for sites whose YAML does not specify
    one.

    Attributes:
        default_per_second: Default sustained request rate, in requests
            per second, for any site whose config does not set
            ``rate_limit``. Must be strictly positive — a zero rate
            would freeze the site, which is never the intended default
            (a disabled site uses ``disabled_sites``, not a zero rate).
        burst_multiplier: How many requests a fresh limiter may send
            back-to-back before pacing kicks in, expressed as a
            multiplier of ``default_per_second``. ``1.0`` means "one
            second of burst", matching the downloader's own default.
        per_site: Per-site overrides of ``default_per_second``. A site
            present in the mapping uses the mapped rate; every other
            site uses the default.
    """

    default_per_second: float = Field(default=1.0, gt=0)
    burst_multiplier: float = Field(default=1.0, ge=1.0)
    per_site: dict[str, float] = Field(default_factory=dict)

    @field_validator("per_site")
    @classmethod
    def _positive_rates(
        cls, value: dict[str, float]
    ) -> dict[str, float]:
        for site_id, rate in value.items():
            if not isinstance(site_id, str) or not site_id:
                raise ValueError(
                    "per_site keys must be non-empty strings"
                )
            if rate <= 0:
                raise ValueError(
                    f"per_site[{site_id!r}] must be > 0, got {rate}"
                )
        return value


