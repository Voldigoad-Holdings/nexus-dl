class RetrySection(_Section):
    """Retry policy applied per page and per task.

    The field names match
    :class:`~nexusdl.core.downloader.retry.RetryPolicy` — see that
    class's docstring for semantics. The values feed
    :func:`nexusdl.core.downloader.retry.policy_from_settings`, which
    reads them via ``getattr`` with its own defaults as fallback, so an
    absent section behaves identically to the section's own defaults.

    Attributes:
        max_attempts: Total attempts per page, including the first.
        initial_delay: Delay before the first retry, in seconds.
        max_delay: Ceiling on the delay between two consecutive
            retries, in seconds.
    """

    max_attempts: int = Field(default=3, ge=1)
    initial_delay: float = Field(default=0.5, ge=0)
    max_delay: float = Field(default=30.0, ge=0)

    @model_validator(mode="after")
    def _delay_ordering(self) -> RetrySection:
        if self.max_delay < self.initial_delay:
            raise ValueError(
                f"max_delay ({self.max_delay}) must be >= initial_delay "
                f"({self.initial_delay})"
            )
        return self


class DownloaderSection(_Section):
    """Download pipeline tuning, consumed by
    :class:`~nexusdl.core.downloader.manager.DownloadManager` and
    :class:`~nexusdl.core.downloader.worker.DownloadWorker`.

    Attributes:
        max_concurrent_tasks: Maximum number of chapters downloaded in
            parallel, pipeline-wide. Fed to
            :class:`~nexusdl.core.downloader.queue.DownloadQueue` at
            construction time.
        max_concurrent_pages: Maximum number of pages downloaded in
            parallel within a single chapter. Fed to the per-worker
            ``asyncio.Semaphore``.
        retry: Retry policy — see :class:`RetrySection`.
        skip_existing: When ``True`` (the default), the manager skips
            chapters whose output file already exists on disk. The
            "re-download this chapter" action in the CLI bypasses this
            by passing ``skip_existing=False`` explicitly.
        default_format: The packaging format used when a caller does not
            specify one. ``CBZ`` is the ecosystem-standard default.
    """

    max_concurrent_tasks: int = Field(default=4, ge=1)
    max_concurrent_pages: int = Field(default=4, ge=1)
    retry: RetrySection = Field(default_factory=RetrySection)
    skip_existing: bool = True
    default_format: PackagingFormat = PackagingFormat.CBZ


